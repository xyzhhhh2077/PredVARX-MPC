function [model,provenance] = validate_crte_source(D,expected_mu)
%VALIDATE_CRTE_SOURCE Require the corrected copyAR model used by copyAV.
assert(isfield(D,'model') && isfield(D,'stats'), ...
    'copyAV:MissingCrteSource','copyAR artifact lacks model or stats.');
assert(isfield(D.stats,'selected_mu'), ...
    'copyAV:MissingCrteSource','copyAR artifact lacks selected_mu.');
if abs(D.stats.selected_mu-expected_mu)>1e-12
    error('copyAV:SourceMuMismatch', ...
        'copyAR selected_mu %.12g does not match expected %.12g.', ...
        D.stats.selected_mu,expected_mu);
end
assert(isfield(D.stats,'ntr_mode') && ...
    any(strcmp(D.stats.ntr_mode,{'paper_trace_normalize', ...
        'paper_trace_normalize_by_mean_trace'})), ...
    'copyAV:SourceNtrMismatch','copyAR artifact lacks paper Ntr provenance.');
raw_names={'S_yu','A_T','C_n'};
assert(all(isfield(D.stats,raw_names)), ...
    'copyAV:SourceNtrMismatch', ...
    'copyAR artifact lacks raw matrices required to recompute paper Ntr.');

ntr_epsilon=10e-6;
Ntr_S_yu=paper_ntr(D.stats.S_yu,ntr_epsilon);
Ntr_A_T=paper_ntr(D.stats.A_T,ntr_epsilon);
Ntr_C_n=paper_ntr(D.stats.C_n,ntr_epsilon);

model=D.model;
provenance=struct( ...
    'source_experiment','copyAR_crte_paper_spectral_validation_unknown_noise', ...
    'selected_mu',D.stats.selected_mu, ...
    'ntr_mode','paper_trace_normalize_by_mean_trace', ...
    'ntr_epsilon',ntr_epsilon, ...
    'ntr_formula','A/max(abs(trace(A))/d,10e-6)', ...
    'Ntr_S_yu',Ntr_S_yu, ...
    'Ntr_A_T',Ntr_A_T, ...
    'Ntr_C_n',Ntr_C_n);
end

function A=paper_ntr(A,epsilon_ntr)
A=(A+A')/2;
d=size(A,1);
assert(d>0 && size(A,2)==d && all(isfinite(A(:))), ...
    'copyAV:SourceNtrMismatch','CRTE Ntr source matrix must be finite and square.');
A=A/max(abs(trace(A))/d,epsilon_ntr);
end